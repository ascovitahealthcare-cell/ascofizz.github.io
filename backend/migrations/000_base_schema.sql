-- ── Hard-delete rows that have been soft-deleted for long enough. ────
-- Retention is a deliberate, operator-invoked action: this is called by
-- the scheduled purge, never by a request path.
create or replace function public.purge_soft_deletes(p_days_old integer default 90)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  cutoff timestamptz := now() - make_interval(days => greatest(p_days_old, 1));
  n_products int; n_customers int; n_orders int; n_coupons int;
begin
  delete from public.products  where deleted_at is not null and deleted_at < cutoff;
  get diagnostics n_products = row_count;
  delete from public.coupons   where deleted_at is not null and deleted_at < cutoff;
  get diagnostics n_coupons = row_count;
  -- Orders are financial records: a soft-deleted order still anchors
  -- refunds, returns and the loyalty ledger, so it is held far longer
  -- than the generic window and never less than seven years.
  delete from public.orders    where deleted_at is not null
                                 and deleted_at < now() - interval '7 years';
  get diagnostics n_orders = row_count;
  delete from public.customers where deleted_at is not null and deleted_at < cutoff
                                 and not exists (
                                   select 1 from public.orders o
                                    where lower(o.customer_email) = lower(customers.email));
  get diagnostics n_customers = row_count;

  return jsonb_build_object('products', n_products, 'coupons', n_coupons,
                            'orders', n_orders, 'customers', n_customers,
                            'cutoff', cutoff);
end;
$$;


-- ── Read-only coupon check. ─────────────────────────────────────────
-- The authoritative claim is claim_coupon_use() (006), which is atomic
-- and mutates. This one only reports whether a code *would* apply, for
-- the storefront's live "apply coupon" feedback.
create or replace function public.validate_coupon(p_code text, p_order_value numeric)
returns jsonb
language plpgsql
stable
security definer
set search_path = public, pg_temp
as $$
declare c public.coupons%rowtype; v_discount numeric;
begin
  select * into c from public.coupons
   where upper(code) = upper(btrim(p_code)) and deleted_at is null;

  if not found                                    then return jsonb_build_object('valid', false, 'reason', 'Coupon not found'); end if;
  if not c.active                                 then return jsonb_build_object('valid', false, 'reason', 'Coupon is not active'); end if;
  if c.expires_at is not null and c.expires_at < now()
                                                  then return jsonb_build_object('valid', false, 'reason', 'Coupon has expired'); end if;
  if c.max_uses is not null and coalesce(c.used_count, 0) >= c.max_uses
                                                  then return jsonb_build_object('valid', false, 'reason', 'Coupon usage limit reached'); end if;
  if c.min_order is not null and p_order_value < c.min_order
                                                  then return jsonb_build_object('valid', false, 'reason',
                                                         format('Minimum order value is %s', c.min_order)); end if;

  v_discount := case when c.type = 'percent'
                     then round(p_order_value * c.value / 100.0, 2)
                     else c.value end;
  if c.max_discount is not null then v_discount := least(v_discount, c.max_discount); end if;
  v_discount := least(v_discount, p_order_value);

  return jsonb_build_object('valid', true, 'discount', v_discount,
                            'type', c.type, 'value', c.value, 'code', c.code);
end;
$$;


