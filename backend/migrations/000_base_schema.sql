-- ASCOFIZZ — BASE SCHEMA
--
-- RUN THIS FIRST, on a brand-new Supabase project, before every other
-- migration in this directory.
--
-- WHY THIS FILE EXISTS
--   The platform this was forked from never had one. Its core tables —
--   orders, customers, products, coupons, refunds, reviews, settings and
--   the rest — were created by hand in the Supabase dashboard over time
--   and only ever existed in that one live project. Every migration in
--   this directory from 001 onward assumes they are already there;
--   db-selfcheck.js calls them "base schema" and has no file to point at.
--   That made the database impossible to stand up from source.
--
--   This file is that missing baseline. It was reconstructed from the
--   application code rather than from a dump, by reading every column the
--   server actually writes and reads:
--     • orders          — the ORDER_COLUMNS whitelist in server.js
--     • products        — the safeFields/arrayFields list in POST
--                         /api/admin/products, plus FRONTEND_OWNED_FIELDS
--     • coupons         — buildCouponPayload() and the validate path
--     • customers       — the insert/update in the order-placement path
--     • everything else — its insert() call sites
--
--   Where the old database's exact type or nullability could not be
--   recovered from code, the choice here is the permissive one, so this
--   never rejects a write the application makes. Constraints that the
--   code clearly relies on (unique coupon codes, unique customer email,
--   the order-id primary key) ARE enforced.
--
-- IDEMPOTENT
--   Every statement is `if not exists` / `or replace`. Safe to re-run.
--
-- ORDER OF EXECUTION
--   000_base_schema.sql   ← this file
--   002_atomic_counters.sql, 003_returns.sql, 004_…, 006_…, 007_…
--   …then the numbered hardening migrations
--   005_rls_lockdown.sql  ← last, after the app is confirmed working
--
--   See MIGRATIONS.md for the full ordered list.
-- ═══════════════════════════════════════════════════════════════════════

