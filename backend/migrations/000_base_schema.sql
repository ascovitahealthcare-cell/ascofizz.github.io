-- BASE-SCHEMA FUNCTIONS
--
--   Migration 011 is an ALTER-only file generated from a live inventory
--   of the production database, and 015 names the trigger functions
--   explicitly. Between them they prove nine functions existed in that
--   database that NO migration in this directory creates — they were
--   made by hand in the dashboard and were never captured anywhere:
--
--     fn_set_updated_at        fn_prevent_negative_stock
--     fn_update_customer_stats fn_auto_log_order_status
--     fn_auto_coupon_usage     fn_sync_order_status
--     vita_ledger_immutable    get_dashboard_kpis
--     purge_soft_deletes       validate_coupon
--
--   Applying 011 or 015 without them fails. They are reconstructed below
--   from their names, from 015's description of how each is invoked, and
--   from the behaviour the application depends on.
--
--   ⚠️ WHICH TRIGGERS ARE ATTACHED, AND WHY NOT ALL OF THEM
--     Three of these functions duplicate work the Node server already
--     does on every write path:
--       • fn_update_customer_stats  — server.js increments
--         customers.total_orders / total_spent itself after each order.
--       • fn_auto_coupon_usage      — coupon uses are claimed atomically
--         through claim_coupon_use() before the order row is written.
--       • fn_auto_log_order_status  — the server inserts its own
--         order_status_logs row, with the acting user in changed_by.
--     Attaching those as triggers on a database whose application also
--     performs the write means every order counts twice, every coupon
--     burns two uses, and the status history doubles. The functions are
--     therefore CREATED (so 011/015 apply, and so the objects match the
--     inventory) but deliberately NOT attached. Attach one only if the
--     corresponding application-side write is removed first.
--
--     The three that ARE attached — fn_set_updated_at,
--     fn_prevent_negative_stock, vita_ledger_immutable — are guards, not
--     counters. They are idempotent and cannot double-count.
-- ═════════════════════════════════════════════════════════════════════

-- ── Attached. Guarantees updated_at even on paths that forget it. ─────
create or replace function public.fn_set_updated_at()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
begin
  new.updated_at := now();
  return new;
end;
$$;

do $$
declare t text;
begin
  foreach t in array array[
    'products','customers','orders','coupons','refunds','reviews',
    'settings','site_media','promo_media','store_contents',
    'ai_actions','auth_token_versions'
  ] loop
    execute format('drop trigger if exists %I on public.%I', 'trg_touch_' || t, t);
    execute format(
      'create trigger %I before update on public.%I
         for each row execute function public.fn_set_updated_at()',
      'trg_touch_' || t, t);
  end loop;
end $$;


-- ── Attached. Stock must never go below zero. ────────────────────────
-- decrement_stock_strict (002) already refuses to oversell, but direct
-- admin edits and the fallback path in sp_place_order both write stock
-- without it. This is the backstop that makes negative stock impossible
-- however the row is reached.
create or replace function public.fn_prevent_negative_stock()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
begin
  if new.stock is null then new.stock := 0; end if;
  if new.stock < 0 then
    raise exception 'Stock cannot be negative (product %, attempted %)', new.id, new.stock
      using errcode = 'check_violation';
  end if;
  return new;
end;
$$;

drop trigger if exists trg_prevent_negative_stock on public.products;
create trigger trg_prevent_negative_stock
  before insert or update of stock on public.products
  for each row execute function public.fn_prevent_negative_stock();


-- ── NOT attached (see the warning above): duplicates server.js. ──────
-- Recomputes a customer's order count and lifetime spend from the orders
-- table. Written as a full recompute rather than a delta so that if it
-- IS ever attached it is self-correcting and cannot drift.
create or replace function public.fn_update_customer_stats()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare v_email text := lower(coalesce(new.customer_email, old.customer_email, ''));
begin
  if v_email = '' then return coalesce(new, old); end if;
  update public.customers c
     set total_orders = sub.n, total_spent = sub.sum_total
    from (
      select count(*) as n, coalesce(sum(o.total), 0) as sum_total
        from public.orders o
       where lower(o.customer_email) = v_email
         and o.deleted_at is null
    ) sub
   where lower(c.email) = v_email;
  return coalesce(new, old);
end;
$$;

